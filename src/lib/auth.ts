/**
 * Роль пользователя в приложении.
 *
 * Используется для:
 * - отображения прав/режима (guest/user/admin)
 * - dev/demo-переключателя ролей в UI
 *
 * NOTE: В продакшене роли обычно приходят из auth/claims,
 * но тип остаётся полезным как единый контракт для фронта.
 */
export type UserRole = "guest" | "user" | "admin";

/**
 * Минимальная информация о пользователе для UI.
 *
 * Поля:
 * - role: текущая роль пользователя
 * - name: отображаемое имя (может отсутствовать, например у гостя)
 */
export type UserInfo = {
  /** Текущая роль пользователя (гость/пользователь/админ). */
  role: UserRole;

  /**
   * Отображаемое имя пользователя.
   * Может отсутствовать (например, в гостевом режиме).
   */
  name?: string;
};
